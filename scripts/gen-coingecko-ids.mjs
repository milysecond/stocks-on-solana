#!/usr/bin/env node
/**
 * Builds src/lib/coingecko-ids.ts: a static map of Solana mint → CoinGecko coin id
 * and top GeckoTerminal pool, so token pages never hit CoinGecko at runtime.
 *
 * Sources: CoinGecko /coins/list?include_platform=true (one call),
 * GeckoTerminal /tokens/multi (30 mints per call, rate limited), every mint in
 * src/lib/*.ts plus the live token list. Run: npm run gen:coingecko
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = { 'User-Agent': 'stocksonsolana.com build', Accept: 'application/json' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJson(url, tries = 6) {
  for (let i = 0; i < tries; i++) {
    const res = await fetch(url, { headers: UA });
    if (res.ok) return res.json();
    if (res.status === 404) return null;
    await sleep(res.status === 429 ? 20000 : 3000);
  }
  throw new Error(`fetch failed: ${url}`);
}

const mints = new Set();
for (const f of readdirSync(join(root, 'src/lib'))) {
  if (!f.endsWith('.ts') || f === 'coingecko-ids.ts') continue;
  const src = readFileSync(join(root, 'src/lib', f), 'utf8');
  for (const m of src.matchAll(/mint:\s*'([1-9A-HJ-NP-Za-km-z]{32,44})'/g)) mints.add(m[1]);
}
try {
  const live = await getJson(`https://stocksonsolana.com/api/token-list?v=${Date.now()}`);
  for (const t of live ?? []) if (t?.mint) mints.add(t.mint);
} catch (e) {
  console.warn('live token list unavailable, using repo mints only', e.message);
}
console.log(`mints: ${mints.size}`);

const list = await getJson('https://api.coingecko.com/api/v3/coins/list?include_platform=true');
const cgByMint = new Map();
for (const c of list) {
  const sol = c.platforms?.solana;
  if (sol && mints.has(sol)) cgByMint.set(sol, c.id);
}
console.log(`coingecko ids: ${cgByMint.size}`);

const poolByMint = new Map();
const all = [...mints];
for (let i = 0; i < all.length; i += 30) {
  const batch = all.slice(i, i + 30);
  const j = await getJson(
    `https://api.geckoterminal.com/api/v2/networks/solana/tokens/multi/${batch.join(',')}?include=top_pools`,
  );
  for (const t of j?.data ?? []) {
    const pool = t.relationships?.top_pools?.data?.[0]?.id; // "solana_<address>"
    if (pool) poolByMint.set(t.attributes.address, pool.replace(/^solana_/, ''));
  }
  process.stdout.write(`\rgeckoterminal ${Math.min(i + 30, all.length)}/${all.length} pools=${poolByMint.size}`);
  await sleep(2200);
}
console.log();

const out = {};
for (const m of [...mints].sort()) {
  const id = cgByMint.get(m);
  const pool = poolByMint.get(m);
  if (id || pool) out[m] = [id ?? '', pool ?? ''];
}
const body = Object.entries(out)
  .map(([m, [id, pool]]) => `  ${JSON.stringify(m)}: [${JSON.stringify(id)}, ${JSON.stringify(pool)}],`)
  .join('\n');
writeFileSync(
  join(root, 'src/lib/coingecko-ids.ts'),
  `// Generated by scripts/gen-coingecko-ids.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n` +
    `// mint → [CoinGecko coin id, top GeckoTerminal Solana pool]. Empty string means none.\n` +
    `// ${mints.size} mints checked · ${cgByMint.size} CoinGecko ids · ${poolByMint.size} GeckoTerminal pools\n` +
    `export const COINGECKO_MAP: Record<string, readonly [string, string]> = {\n${body}\n};\n`,
);
console.log(`wrote ${Object.keys(out).length} entries`);
